#!/usr/bin/env python3
"""Inventory repository entry points and executable documentation commands."""

from __future__ import annotations

import argparse
import ast
from collections import Counter
from pathlib import Path
import re

from inventory_common import classify, markdown_table, relative, tracked_files


DOC_COMMAND = re.compile(
    r"^\s*(?:\$\s*)?(?:python(?:3)?\b|\"?\$PYTHON\"?\b|make\b|pytest\b|"
    r"(?:bash\s+)?(?:\./)?(?:scripts|examples)/|(?:\./)?(?:dcp_optimizer|validate_dcps)\.py\b)"
)
MAKE_TARGET = re.compile(r"^([A-Za-z0-9_.-]+)\s*:(?![=])", re.MULTILINE)
FENCE = re.compile(r"```(?:bash|sh|shell|console|python)?\s*\n(.*?)```", re.DOTALL | re.IGNORECASE)


def has_main_guard(path: Path) -> bool:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (OSError, SyntaxError, UnicodeDecodeError):
        return False
    for node in ast.walk(tree):
        if not isinstance(node, ast.If):
            continue
        test = node.test
        if not isinstance(test, ast.Compare) or not isinstance(test.left, ast.Name):
            continue
        if test.left.id != "__name__" or len(test.comparators) != 1:
            continue
        value = test.comparators[0]
        if isinstance(value, ast.Constant) and value.value == "__main__":
            return True
    return False


def inventory(repo: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    files = tracked_files(repo)
    for path in files:
        if not path.exists():
            continue
        rel = relative(path, repo)
        kind = ""
        detail = ""
        if path.suffix == ".py" and (has_main_guard(path) or path.stat().st_mode & 0o111):
            executable = bool(path.stat().st_mode & 0o111)
            kind = "python"
            detail = "__main__ guard" if has_main_guard(path) else "executable Python surface"
            if executable and detail == "__main__ guard":
                detail += ", executable"
        elif path.suffix == ".sh":
            executable = path.stat().st_mode & 0o111
            kind = "shell"
            detail = "executable script" if executable else "shell surface/helper"
        elif rel == "Makefile":
            targets = [target for target in MAKE_TARGET.findall(path.read_text()) if target != ".PHONY"]
            kind, detail = "make", ", ".join(targets)
        elif path.suffix == ".md":
            text = path.read_text(encoding="utf-8", errors="replace")
            commands = [line.strip() for block in FENCE.findall(text) for line in block.splitlines() if DOC_COMMAND.match(line)]
            if commands:
                kind, detail = "documentation", f"{len(commands)} executable command line(s)"
        if not kind:
            continue
        lifecycle, owner, target = classify(rel)
        rows.append(
            {
                "path": rel,
                "kind": kind,
                "detail": detail,
                "class": lifecycle,
                "owner": owner,
                "migration_target": target,
            }
        )
    return sorted(rows, key=lambda row: (row["class"], row["path"], row["kind"]))


def render(rows: list[dict[str, str]]) -> str:
    counts = Counter(row["class"] for row in rows)
    summary = ", ".join(f"{key}={counts[key]}" for key in sorted(counts))
    table_rows = [
        [row["path"], row["kind"], row["detail"], row["class"], row["owner"], row["migration_target"]]
        for row in rows
    ]
    return "\n".join(
        [
            "# Entry-point Inventory",
            "",
            "Generated by `tools/audit_entries.py`. Do not infer inactivity from a directory name; the class and migration target are explicit review inputs.",
            "",
            f"Inventory totals: {len(rows)} surfaces ({summary}).",
            "",
            markdown_table(["Path", "Kind", "Detail", "Class", "Current owner", "Migration target"], table_rows),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, help="Write Markdown to this path instead of stdout.")
    args = parser.parse_args()
    report = render(inventory(args.repo.resolve()))
    if args.output:
        args.output.write_text(report, encoding="utf-8")
    else:
        print(report, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
